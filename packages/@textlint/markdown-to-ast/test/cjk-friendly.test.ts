import { describe, it } from "vitest";
import assert from "node:assert";
import fs from "node:fs";
import type { TxtNode, TxtParentNode } from "@textlint/ast-node-types";
import { parse } from "../src/index.js";

type AnyNode = TxtNode & { children?: AnyNode[]; value?: string };

const escapeHtml = (s: string) =>
    s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const TAGS: Record<string, string> = { Emphasis: "em", Strong: "strong", Delete: "s" };
/**
 * Render inline nodes as the HTML of markdown-it, for emphasis, strong emphasis, and strikethrough
 */
const render = (nodes: AnyNode[]): string =>
    nodes
        .map((node) => {
            if (node.type === "Str") {
                return escapeHtml(node.value ?? "");
            }
            const tag = TAGS[node.type];
            if (tag === undefined) {
                throw new Error(`Unexpected node: ${node.type}`);
            }
            return `<${tag}>${render(node.children ?? [])}</${tag}>`;
        })
        .join("");
const renderParagraph = (text: string, cjkFriendlyEmphasis?: boolean) => {
    const ast = parse(text, cjkFriendlyEmphasis === undefined ? undefined : { cjkFriendlyEmphasis });
    const paragraph = ast.children[0] as TxtParentNode;
    assert.strictEqual(paragraph.type, "Paragraph");
    return render(paragraph.children as AnyNode[]);
};

describe("cjkFriendlyEmphasis", () => {
    it("closes strong emphasis after CJK punctuation", () => {
        assert.strictEqual(renderParagraph("**強調。**この文", true), "<strong>強調。</strong>この文");
    });
    it("follows CommonMark without the option", () => {
        assert.strictEqual(renderParagraph("**強調。**この文"), "**強調。**この文");
        assert.strictEqual(renderParagraph("**強調。**この文", false), "**強調。**この文");
    });
    it("recognizes strikethrough after CJK punctuation", () => {
        assert.strictEqual(renderParagraph("~~削除。~~この文", true), "<s>削除。</s>この文");
        assert.strictEqual(renderParagraph("~削除。~この文", true), "<s>削除。</s>この文");
        assert.strictEqual(renderParagraph("~~削除。~~この文"), "~~削除。~~この文");
    });
    it("keeps the ranges of the nodes", () => {
        const text = "前の**強調。**この文";
        const ast = parse(text, { cjkFriendlyEmphasis: true });
        const paragraph = ast.children[0] as TxtParentNode;
        const strong = paragraph.children[1];
        assert.strictEqual(strong.type, "Strong");
        assert.deepStrictEqual(strong.range, [2, 9]);
        assert.strictEqual(strong.raw, "**強調。**");
    });
    it("does not record the option in the AST", () => {
        const text = "**強調。**この文";
        const withOption = parse(text, { cjkFriendlyEmphasis: true });
        assert.deepStrictEqual(Object.keys(withOption), Object.keys(parse(text)));
    });
    it("gives the same AST without CJK characters", () => {
        const text = 'a**(b)**c *a* _b_ __c__ ~~d~~ x*"y"*z foo_bar_ **a.**b';
        assert.deepStrictEqual(parse(text, { cjkFriendlyEmphasis: true }), parse(text));
    });
    it("does not use the option of the previous call", () => {
        parse("**強調。**この文", { cjkFriendlyEmphasis: true });
        assert.strictEqual(renderParagraph("**強調。**この文"), "**強調。**この文");
    });
    it("ignores unknown options", () => {
        const text = "**強調。**この文";
        assert.deepStrictEqual(parse(text, { unknown: true } as never), parse(text));
    });

    describe("agrees with markdown-it-cjk-friendly", () => {
        // generated by tools/create-cjk-friendly-fixture.mjs
        const cases: { input: string; html: string }[] = JSON.parse(
            fs.readFileSync(new URL("./cjk-friendly/cases.json", import.meta.url), "utf-8")
        );
        it(`renders ${cases.length} cases as the reference implementation`, () => {
            const failures = cases.filter(({ input, html }) => renderParagraph(input, true) !== html);
            assert.deepStrictEqual(
                failures.map(({ input, html }) => ({ input, expected: html, actual: renderParagraph(input, true) })),
                []
            );
        });
    });
});
