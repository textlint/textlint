// Generate src/cjk.ts from the ranges of the CommonMark CJK-friendly Amendments.
// Usage: node tools/generate-cjk.mjs <path-to-ranges.md>
// ranges.md: https://github.com/tats-u/markdown-cjk-friendly/blob/main/ranges.md
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
    throw new Error("Usage: node tools/generate-cjk.mjs <path-to-ranges.md>");
}
const md = fs.readFileSync(input, "utf-8");
const version = /## Unicode Version\s+(\d+)/.exec(md)?.[1];
const section = /## CJK characters\n([\s\S]*?)\n(?:<details>|## )/.exec(md)?.[1];
if (!version || !section) {
    throw new Error("Unexpected format of ranges.md");
}
const ranges = [];
for (const m of section.matchAll(/^- U\+([0-9A-F]+)(?:\.\.U\+([0-9A-F]+))?/gm)) {
    const start = parseInt(m[1], 16);
    const end = m[2] ? parseInt(m[2], 16) : start;
    ranges.push(start, end);
}
for (let i = 2; i < ranges.length; i += 2) {
    if (ranges[i] <= ranges[i - 1]) {
        throw new Error("Ranges must be sorted and must not overlap");
    }
}
const hex = (n) => `0x${n.toString(16)}`;
const rows = [];
for (let i = 0; i < ranges.length; i += 2) {
    rows.push(`    ${hex(ranges[i])}, ${hex(ranges[i + 1])},`);
}
const out = `// This file is generated by tools/generate-cjk.mjs. DO NOT EDIT.
// Source: https://github.com/tats-u/markdown-cjk-friendly/blob/main/ranges.md (Unicode ${version})
// Pairs of the first and the last code point of each range of CJK characters.
// prettier-ignore
const CJK_RANGES = new Int32Array([
${rows.join("\n")}
]);
/**
 * Return true if the code point is a CJK character of the CommonMark CJK-friendly Amendments.
 */
export function isCjkCodePoint(cp: number): boolean {
    if (cp < CJK_RANGES[0] || cp > CJK_RANGES[CJK_RANGES.length - 1]) {
        return false;
    }
    let lo = 0;
    let hi = (CJK_RANGES.length >> 1) - 1;
    while (lo <= hi) {
        const mid = (lo + hi) >> 1;
        if (cp < CJK_RANGES[mid * 2]) {
            hi = mid - 1;
        } else if (cp > CJK_RANGES[mid * 2 + 1]) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}
`;
fs.writeFileSync(fileURLToPath(new URL("../src/cjk.ts", import.meta.url)), out);
