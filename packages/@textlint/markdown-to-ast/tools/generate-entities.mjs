// Generate src/entities.ts from the WHATWG HTML named character reference list.
// Usage: node tools/generate-entities.mjs <path-to-entities.json>
// entities.json: https://html.spec.whatwg.org/entities.json
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
    throw new Error("Usage: node tools/generate-entities.mjs <path-to-entities.json>");
}
const json = JSON.parse(fs.readFileSync(input, "utf-8"));
const names = [];
const values = [];
for (const key of Object.keys(json).sort()) {
    // Markdown only supports references that end with `;`
    if (!key.endsWith(";")) {
        continue;
    }
    names.push(key.slice(1, -1));
    values.push(json[key].characters);
}
const escape = (s) =>
    JSON.stringify(s).replace(/[\u007f-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
const out = `// This file is generated by tools/generate-entities.mjs. DO NOT EDIT.
// Source: https://html.spec.whatwg.org/entities.json
const NAMES = ${escape(names.join(","))};
const VALUES = ${escape(values.join("\u0000"))};
let table: Map<string, string> | undefined;
/**
 * Decode a named character reference like \`amp\` (without \`&\` and \`;\`).
 * Return undefined if the name is unknown.
 */
export function decodeNamedEntity(name: string): string | undefined {
    if (table === undefined) {
        table = new Map();
        const names = NAMES.split(",");
        const values = VALUES.split("\\u0000");
        for (let i = 0; i < names.length; i++) {
            table.set(names[i], values[i]);
        }
    }
    return table.get(name);
}
`;
fs.writeFileSync(fileURLToPath(new URL("../src/entities.ts", import.meta.url)), out);
console.log(`generated ${names.length} entities`);
